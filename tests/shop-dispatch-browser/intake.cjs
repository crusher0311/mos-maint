const {chromium}=require("../../artifacts/detect-dog-workflow/node_modules/@playwright/test");
const assert=require("node:assert/strict");
(async()=>{
 const browser=await chromium.launch({executablePath:process.env.DEMO_CHROMIUM_PATH,headless:true});
 const page=await browser.newPage({viewport:{width:1300,height:1000}}),errors=[];
 page.on("pageerror",e=>errors.push(e.message));
 page.on("dialog",dialog=>dialog.accept());
 await page.goto("http://127.0.0.1:24100/intake.html?appointment&timeout");
 await page.getByLabel("I explicitly confirm").check();
 await page.getByRole("button",{name:"Record local check-in"}).click();
 await page.getByRole("button",{name:"Retry identical intake request"}).waitFor();
 const first=await page.evaluate(()=>window.intakeRequests[0]);
 await page.reload();
 await page.getByRole("button",{name:"Retry identical intake request"}).click();
 await page.getByRole("button",{name:"Open checked-in visit"}).first().waitFor();
 assert.equal(await page.evaluate(()=>window.intakeRequests[0]),first);
 assert.equal(await page.evaluate(()=>JSON.parse(sessionStorage.getItem("offline:intake:board")).visits.length),1);
 await page.getByRole("button",{name:"Open checked-in visit"}).first().click();
 await page.getByLabel("I explicitly confirm creation").check();
 await page.getByRole("button",{name:"Create upstream ticket"}).click();
 await page.getByText("Ticket outcome uncertain",{exact:true}).waitFor();
 await page.reload();
 await page.getByRole("button",{name:"Open checked-in visit"}).first().click();
 await page.getByRole("button",{name:"Retry verification only"}).click();
 await page.getByText("Confirmed ticket",{exact:true}).waitFor();
 assert.equal(await page.evaluate(()=>JSON.parse(sessionStorage.getItem("offline:intake:board")).visits.length),1);
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 assert.deepEqual(errors,[]);
 const walk=await browser.newPage();await walk.goto("http://127.0.0.1:24100/intake.html");
 await walk.getByLabel("Customer display name").fill("Walk-in Customer");
 await walk.getByLabel("Vehicle display description").fill("Walk-in sedan");
 await walk.getByLabel("Customer concerns").fill("Inspect tires");
 await walk.getByRole("button",{name:"Record local check-in"}).click();
 await walk.getByRole("button",{name:"Open checked-in visit"}).first().click();
 await walk.getByText("Save intake with a confirmed existing or new customer and vehicle first.").waitFor();
 await walk.getByLabel("Existing upstream RO number").fill("501");
 await walk.getByRole("button",{name:"Look up official ticket"}).click();
 await walk.getByLabel("I confirm the displayed customer").check();
 await walk.getByRole("button",{name:"Verify & link existing ticket"}).click();
 await walk.getByText("Linked upstream work order:").waitFor();
 await browser.close();console.log("Offline intake UI passed: appointment prefill, accepted timeout/reload/identical retry, explicit creation, verification recovery, walk-in missing identity, reviewed RO link and mobile layout.");
})().catch(e=>{console.error(e);process.exit(1)});
