export const crmAgencies = pgTable("crm_agencies", {
  id: varchar("id").primaryKey().default(sql`gen_random_uuid()`),
  name: text("name").notNull(),
  slug: text("slug").notNull().unique(),
  type: text("type").notNull().default("marketing"),
  status: text("status").notNull().default("Active"),
  logo: text("logo"),
  primaryColor: text("primary_color").default("#3c81c3"),
  secondaryColor: text("secondary_color").default("#1e5a8a"),
  contactEmail: text("contact_email"),
  contactPhone: text("contact_phone"),
  stripeAccountId: text("stripe_account_id"),
  stripeOnboarded: boolean("stripe_onboarded").default(false),
  commissionRate: decimal("commission_rate", { precision: 5, scale: 2 }).default("10.00"),
  favicon: text("favicon"),
  avatar: text("avatar"),
  tagline: text("tagline"),
  slogan: text("slogan"),
  corporateWebsite: text("corporate_website"),
  appStoreLink: text("app_store_link"),
  playStoreLink: text("play_store_link"),
  brandingThemeId: varchar("branding_theme_id"),
  headerColor: text("header_color"),
  buttonColor: text("button_color"),
  buttonTextColor: text("button_text_color"),
  borderColor: text("border_color"),
  accentColor: text("accent_color"),
  backgroundColor: text("background_color"),
  sidebarColor: text("sidebar_color"),
  cardColor: text("card_color"),
  createdAt: timestamp("created_at").notNull().defaultNow(),
  archivedAt: timestamp("archived_at"),
}, (table) => ({
  slugIdx: index("crm_agencies_slug_idx").on(table.slug),
  statusIdx: index("crm_agencies_status_idx").on(table.status),
}));

