export const crmLocations = pgTable("crm_locations", {
  id: varchar("id").primaryKey().default(sql`gen_random_uuid()`),
  accountId: varchar("account_id").notNull().references(() => crmAccounts.id, { onDelete: "cascade" }),
  parentOrganizationId: varchar("parent_organization_id").references(() => crmParentOrganizations.id),
  agencyId: varchar("agency_id").references(() => crmAgencies.id),
  name: text("name").notNull(),
  address: text("address"),
  city: text("city"),
  state: text("state"),
  zip: text("zip"),
  phone: text("phone"),
  timezone: text("timezone").default("America/Chicago"),
  smsNumber: text("sms_number"),
  linkedShopId: integer("linked_shop_id"),
  createdAt: timestamp("created_at").notNull().defaultNow(),
  archivedAt: timestamp("archived_at"),
}, (table) => ({
  accountIdx: index("crm_locations_account_idx").on(table.accountId),
  parentOrgIdx: index("crm_locations_parent_org_idx").on(table.parentOrganizationId),
}));

export const crmUserTypes = pgTable("crm_user_types", {
  id: varchar("id").primaryKey().default(sql`gen_random_uuid()`),
  name: text("name").notNull(),
  bucket: text("bucket").notNull().default("account"),
  description: text("description"),
  permissions: jsonb("permissions").$type<Record<string, boolean>>().default(sql`'{}'::jsonb`),
  sortOrder: integer("sort_order").default(0),
  createdAt: timestamp("created_at").notNull().defaultNow(),
});

export const crmAgencyPricingPackages = pgTable("crm_agency_pricing_packages", {
  id: varchar("id").primaryKey().default(sql`gen_random_uuid()`),
  agencyId: varchar("agency_id").notNull().references(() => crmAgencies.id, { onDelete: "cascade" }),
  name: text("name").notNull(),
  description: text("description"),
  monthlyPrice: decimal("monthly_price", { precision: 10, scale: 2 }).notNull(),
  features: text("features").array(),
  isActive: boolean("is_active").notNull().default(true),
  sortOrder: integer("sort_order").default(0),
  createdAt: timestamp("created_at").notNull().defaultNow(),
});

