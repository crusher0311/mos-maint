export function getJobKnowledgeBase(): JobKnowledgeEntry[] {
  return JOB_KNOWLEDGE_BASE;
}

export function searchJobs(query: string, limit = 10): JobKnowledgeEntry[] {
  const queryLower = query.toLowerCase();
  const words = queryLower.split(/\s+/).filter(w => w.length >= 2);

  const scored = JOB_KNOWLEDGE_BASE.map(job => {
    let score = 0;
    const searchable = `${job.title} ${job.category} ${job.technicalDescription} ${job.tags.join(' ')}`.toLowerCase();
    for (const word of words) {
      if (job.title.toLowerCase().includes(word)) score += 10;
      if (job.category.toLowerCase().includes(word)) score += 5;
      if (job.tags.some(t => t.includes(word))) score += 3;
      if (searchable.includes(word)) score += 1;
    }
    return { job, score };
  }).filter(item => item.score > 0);

  scored.sort((a, b) => b.score - a.score);
  return scored.slice(0, limit).map(item => item.job);
}

export function getJobById(jobId: string): JobKnowledgeEntry | undefined {
  return JOB_KNOWLEDGE_BASE.find(j => j.jobId === jobId);
}

export function getJobsByCategory(category: string): JobKnowledgeEntry[] {
  return JOB_KNOWLEDGE_BASE.filter(j => j.category.toLowerCase() === category.toLowerCase());
}

export function getCompanionJobs(jobId: string): JobKnowledgeEntry[] {
  const job = getJobById(jobId);
  if (!job) return [];
  return job.companionJobs.map(id => getJobById(id)).filter(Boolean) as JobKnowledgeEntry[];
}

export function getUpsellJobs(jobId: string): JobKnowledgeEntry[] {
  const job = getJobById(jobId);
  if (!job) return [];
  return job.upsellJobs.map(id => getJobById(id)).filter(Boolean) as JobKnowledgeEntry[];
}

export async function seedJobKnowledgeBase(): Promise<{ inserted: number }> {
  const db = await getDb();
  const collection = db.collection(ESTIMATE_COLLECTIONS.jobKnowledgeBase);

  const existing = await collection.countDocuments();
  if (existing > 0) {
    await collection.deleteMany({});
  }

  const docs = JOB_KNOWLEDGE_BASE.map(job => ({
    ...job,
    createdAt: new Date(),
    updatedAt: new Date(),
  }));

  const result = await collection.insertMany(docs);
  
  await collection.createIndex({ jobId: 1 }, { unique: true });
  await collection.createIndex({ category: 1 });
  await collection.createIndex({ title: "text", technicalDescription: "text", tags: "text" });
  await collection.createIndex({ tags: 1 });

  return { inserted: result.insertedCount };
}

export async function getShopHistoricalAverage(
  shopId: number,
  jobTitle: string,
  vehicleAttributes?: { make?: string; model?: string; year?: number }
): Promise<{ avgHours: number; avgTotal: number; avgLaborTotal: number; avgPartsTotal: number; count: number } | null> {
  try {
    const db = await getDb();
    const matchConditions: any = {
      shopId,
      'softDelete.isDeleted': { $ne: true },
      status: { $in: ['completed', 'authorized'] },
    };

    const titleWords = jobTitle.toLowerCase().split(/\s+/).filter(w => w.length >= 2);
    if (titleWords.length > 0) {
      matchConditions.$and = titleWords.map(word => ({
        title: { $regex: word.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'), $options: 'i' },
      }));
    }

    const pipeline: any[] = [
      { $match: matchConditions },
      {
        $group: {
          _id: null,
          avgHours: { $avg: { $ifNull: ['$laborHoursBilled', '$laborHoursActual'] } },
          avgTotal: { $avg: '$total' },
          avgLaborTotal: { $avg: '$laborTotal' },
          avgPartsTotal: { $avg: '$partsTotal' },
          count: { $sum: 1 },
        },
      },
    ];

    const results = await db.collection('normalized_service_jobs').aggregate(pipeline).toArray();
    if (results.length === 0 || results[0].count === 0) return null;

    const r = results[0];
    return {
      avgHours: Math.round((r.avgHours || 0) * 10) / 10,
      avgTotal: Math.round((r.avgTotal || 0) * 100) / 100,
      avgLaborTotal: Math.round((r.avgLaborTotal || 0) * 100) / 100,
      avgPartsTotal: Math.round((r.avgPartsTotal || 0) * 100) / 100,
      count: r.count,
    };
  } catch {
    return null;
  }
}
