import { randomUUID } from "node:crypto";
import { appendRatingTag, buildFindingsNote, buildInspectionLineTitle, buildVhiContextNote } from "../compose";
import { canonical, DurableError, VERSION, validSnapshot, type Request, type Snapshot, type Plan } from "./model";

export const TITLE = "Vehicle Inspection (MOS Auto DVI)";
export function composePlan(request: Request, snapshot: Snapshot, extras: Array<{title: string; hours: number; rate: number}>): Plan {
  if (!validSnapshot(snapshot, snapshot.target)) throw new DurableError("UNVERIFIED_TARGET");
  const labels = snapshot.resultLabels;
  if (!labels || labels.source !== "shop_configuration" || !labels.evidence?.trim() ||
      canonical(labels.target) !== canonical(snapshot.target) ||
      [labels.green, labels.yellow, labels.red].some(v => typeof v !== "string" || !v.trim()) ||
      new Set([labels.green, labels.yellow, labels.red]).size !== 3)
    throw new DurableError("RESULT_LABELS_UNVERIFIED", 503);
  const existing = snapshot.body.ServicePackages.ItemCollection;
  // Never adopt historical packages by a display name/code. Changed inspections
  // require an explicitly adopted ownership baseline, not a new random package.
  if (existing.some((p: any) => String(p.Code || "").startsWith("MOS-") || p.ServicePackageHeader?.Title === TITLE))
    throw new DurableError("OWNERSHIP_ADOPTION_REQUIRED");
  const labor = (description: string, rank: number, hours = 0, rate = 0) => {
    const total = (Math.round(hours * rate * 100) / 100).toFixed(2);
    return { ID: randomUUID(), Rank: rank, Type: "Labor", Description: description,
      Quantity: String(hours), RateCode: "1", TechnicianHour: String(hours), Price: rate.toFixed(2),
      Total: total, ExtendedTotal: total, MinimumCharge: 0, Discount: 0, TotalCost: "0.00", Completed: false };
  };
  const evidenceId = randomUUID();
  const evidence = { ID: evidenceId, Chapter: "Service", Code: `MOS-DVI-${evidenceId}`, Rank: existing.length + 1,
    ServicePackageHeader: {Title: TITLE, Description: buildFindingsNote(request.items) || "[Auto DVI — generated by MOS]"},
    ServicePackageLines: {ItemCollection: request.items.map((i, n) =>
      labor(appendRatingTag(buildInspectionLineTitle(i.name, i.serviceKey), i.rating), n + 1))} };
  if (extras.some(e => !e.title || !Number.isFinite(e.hours) || !Number.isFinite(e.rate) || e.hours < 0 || e.rate < 0))
    throw new DurableError("INVALID_PRICING", 503);
  const packages = extras.map((e, n) => {
    const id = randomUUID();
    return {ID: id, Chapter: "Service", Code: `MOS-REC-${id}`, Rank: existing.length + n + 2,
      ServicePackageHeader: {Title: e.title, Description: "[Recommended from vehicle maintenance plan — MOS Auto DVI]"},
      ServicePackageLines: {ItemCollection: [labor(e.title, 1, e.hours, e.rate)]}};
  });
  const inspection = {ID: randomUUID(), Chapter: "Inspection",
    ServicePackageHeader: {Title: TITLE, Description: "[Auto DVI — generated by MOS]"},
    ServicePackageInspectionLines: {ItemCollection: request.items.map((i, n) => ({
      ID: randomUUID(), Rank: n + 1, Type: "Line", Title: i.name,
      Result: i.rating ? labels[i.rating] : "",
      Notes: [buildVhiContextNote({source: i.source, bucket: i.bucket, action: i.action,
        dueAtMiles: i.dueAtMiles, milesToGo: i.milesToGo, notes: i.itemNotes}),
        i.notes, i.recommendation ? `Recommend: ${i.recommendation}` : ""].filter(Boolean).join(" — "),
    }))}};
  const packageBody = structuredClone(snapshot.body);
  packageBody.ServicePackages.ItemCollection.push(evidence, ...packages);
  const finalBody = structuredClone(packageBody);
  finalBody.ServicePackages.ItemCollection.push(inspection);
  return { version: VERSION, target: snapshot.target, baseline: snapshot,
    // WorkOrder additions only: never echo GET fields or resubmit unrelated
    // packages, and never express removal using empty arrays/DeletionTime.
    payloads: {packages: {ID: snapshot.target.guid, ServicePackages: {ItemCollection: [evidence, ...packages]}},
      findings: {ItemCollection: [inspection]}},
    desired: {packages: packageBody, findings: finalBody},
    itemKeys: [...request.items.map((_, n) => `finding:${n}`), ...extras.map((_, n) => `recommendation:${n}`)],
    lineCount: request.items.length, recommendedCount: extras.length };
}
